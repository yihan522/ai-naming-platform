-- 1. 起名历史表
create table if not exists public.name_history (
  id               bigint generated by default as identity primary key,
  user_requirement text not null,                 -- 用户起名需求
  name_result      text not null,                 -- 模型生成的名字方案全文
  model_name       text not null,                 -- 使用的模型（label / model）
  created_at       timestamptz not null default now()
);

-- 2. 常用索引：按时间倒序取最近记录
create index if not exists idx_name_history_created_at
  on public.name_history (created_at desc);

-- 3. 开启行级安全 RLS
alter table public.name_history enable row level security;

